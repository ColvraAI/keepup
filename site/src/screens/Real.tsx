'use client';

import type { ReactNode } from 'react';
import { useBundle } from '@/components/BundleContext';
import { Ext } from '@/components/Ext';
import { ScreenHead } from '@/components/parts';
import { count, longDate, shortDate, shortSha, usd } from '@/lib/format';
import { allEvents, prOverridingRefusal } from '@/lib/replay';
import { labLabel, patchesLine } from '@/lib/repos';
import { firstRunCost } from '@/lib/runs';

function Row({ thing, source, check }: { thing: ReactNode; source: ReactNode; check: ReactNode }) {
  return (
    <tr>
      <td>{thing}</td>
      <td>{source}</td>
      <td>{check}</td>
    </tr>
  );
}

export function RealScreen() {
  const bundle = useBundle();
  const { pulse, manifest, prs, runs, replay, replayChecks, checks, weekly } = bundle;
  const issues = weekly.filter((brief) => brief.issue);
  const rows = replay.repos.flatMap(allEvents);
  const engineRows = rows.filter((row) => row.run).length;
  const rowTotal = rows.length;
  const main = runs.find((run) => run.repo === replay.repos[0]?.repo && !run.provider_only);
  const judgeCost = main ? firstRunCost(main) : 0;
  const points = replay.repos.flatMap((repo) => repo.summary.team_points);
  const commits = new Set(points.map((point) => point.commit)).size;
  const pointsNote = `The ${points.length} counted team points are ${commits === 1 ? 'one commit' : `${commits} commits`}.`;
  const exception = main?.held_back.map((row) => prOverridingRefusal(row.thing, prs)).find(Boolean);
  const conflictLine = exception ? `The engine held back part of what PR ${exception.id} adds, and both screens say so.` : '';
  return (
    <section className="screen real" data-screen="real">
      <ScreenHead
        eyebrow="How this is real"
        title="Real inputs. Simulated time and place."
        lede="Every item, date, price and number from the data is read at build time. The words around them, and the Moonshot assumptions, are ours. Here’s where each part comes from, so you can check any of it."
      />

      <section className="real__block">
        <h2 className="h2">What’s on GitHub today</h2>
        {manifest.github.exists ? (
          <p className="lede" data-testid="github-state">Org {manifest.github.org}: {manifest.github.pull_requests} pull requests and {manifest.github.issues} issues, listed in <code>data/github-objects.json</code>.</p>
        ) : (
          <p className="lede" data-testid="github-state">Nothing. The keepup App isn’t registered yet, and <code>data/github-objects.json</code> is the only thing on this site allowed to say otherwise. There are {patchesLine(prs)}, each shown with its diff and base commit and labelled “Ready to open”. Links to code point at the upstream repo at the pinned commit, read only.</p>
        )}
      </section>

      <section className="real__block">
        <h2 className="h2">What’s simulated</h2>
        <div className="table-wrap">
          <table className="data">
            <thead><tr><th>What</th><th>How</th></tr></thead>
            <tbody>
              <tr>
                <td>Time</td>
                <td>The replay runs {longDate(replay.window.from)} to {longDate(replay.window.to)} as if keepup had been installed on the first day. Each pull request is built on the repo as it was that day, with two exceptions: AURA’s early bases were on its nightly branch, not main, and the Claude-only PR 01 sits on an earlier base than the last commit before its date. The database is the {longDate(replay.window.fetched)} one and the pattern list is today’s: moving the clock doesn’t remove newer records, so a run “as of” a date shows the route to a finding, not what the product would have seen that day.</td>
              </tr>
              <tr>
                <td>What keepup did</td>
                <td>Each row’s action is written in <code>data/timeline.json</code>. {engineRows} of its {rowTotal} rows were reached by a live run, and are marked “engine run”; the rest are marked “specified by hand”. The patches were written by hand from <code>docs/prs</code>, not generated by the engine, and <code>data/finding-prs.json</code> is a person’s list of which pull request answers which finding. {conflictLine}</td>
              </tr>
              <tr>
                <td>Place</td>
                <td>Pull requests belong on forks in a demo org, opened by the keepup App, never on upstream repos. Until the App exists they stay local (decision D11).</td>
              </tr>
            </tbody>
          </table>
        </div>
      </section>

      <section className="real__block">
        <h2 className="h2">What’s real, and where to check it</h2>
        <div className="table-wrap">
          <table className="data">
            <thead><tr><th>On screen</th><th>Source</th><th>Check it</th></tr></thead>
            <tbody>
              <Row thing={`${count(pulse.total)} new or updated things, ${pulse.by_source.length} sources`} source={<code>data/db</code>} check={`Fetched ${longDate(pulse.window.fetched)}. ${count(pulse.in_window)} dated in the window. Every feed line links to its source.`} />
              <Row thing="Repos, files and lines" source={<code>data/timeline.json</code>} check="Every file:line is a permalink at a pinned commit." />
              <Row thing="What we understood, findings, held back" source={<code>data/runs/*.json</code>} check={`${runs.length} recorded runs of the real pipeline, each with its checks. Newest ${longDate(runs.map((run) => run.scanned_at).sort().at(-1) ?? '')}. They’re rebuilt from the saved answers in data/replay, so a model step’s time on screen isn’t a model’s; the first run of AnythingLLM’s judge cost ${usd(judgeCost)}.`} />
              <Row thing="“Your team shipped it”" source="The upstream repo’s git history" check={`Commit links on every line. Computed: ${replay.headline}`} />
              <Row thing="Pull request diffs" source={<code>lab/*/patches</code>} check={`${prs.length} pull requests, ${prs.reduce((sum, pr) => sum + pr.stages.length, 0)} commits, from git format-patch at each base commit.`} />
              <Row thing="Prices" source={<code>data/db</code>} check="OpenRouter records with a fetch date, and the cache lines quoted from the provider’s own changelog." />
              <Row thing="The one line in Claude Code" source={<code>data/recorded/keepup-check.json</code>} check={checks[0] ? `Real output of keepup check, recorded ${longDate(checks[0].recorded_at)}.` : 'Not recorded yet.'} />
              <Row thing="Weekly briefs" source={<code>app/src/brief.ts</code>} check={`${weekly.length} briefs rendered from the timeline. ${issues.length} posted as issues.`} />
            </tbody>
          </table>
        </div>
      </section>

      <section className="real__block">
        <h2 className="h2">The labs: measured, or says so</h2>
        <div className="table-wrap">
          <table className="data" data-testid="labs-table">
            <thead><tr><th>Pull request</th><th>Lab</th><th>State, read from its result file</th></tr></thead>
            <tbody>
              {prs.map((pr) => (
                <tr key={pr.id}>
                  <td className="mono">{pr.id}</td>
                  <td className="mono">{pr.lab.dir}</td>
                  <td>{pr.lab.status === 'measured' ? `${labLabel(pr)}: ${pr.lab.title_number ?? 'see its table'}` : labLabel(pr)}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </section>

      <section className="real__block">
        <h2 className="h2">Live checks behind the replay</h2>
        <p className="small real__note">Runs of the real pipeline at the replay’s own base commits, with Claude as the judge. They use the {longDate(replay.window.fetched)} database and today’s pattern list, so they show the route to a finding, not what the product saw on the day.</p>
        <div className="table-wrap">
          <table className="data">
            <thead><tr><th>Repo at commit</th><th>As of</th><th>Findings</th><th>Spent</th></tr></thead>
            <tbody>
              {replayChecks.map((check) => (
                <tr key={check.file}>
                  <td className="mono">{check.repo}@{shortSha(check.commit)}</td>
                  <td>{shortDate(check.as_of)}</td>
                  <td>{check.findings.length}</td>
                  <td className="num">{usd(check.usd)}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
        <p className="small real__note">{pointsNote} Code links: <Ext href={replay.repos[0]?.pinned_url}>{replay.repos[0]?.repo}</Ext> and <Ext href={replay.repos[1]?.pinned_url}>{replay.repos[1]?.repo}</Ext> at their pinned commits.</p>
      </section>
    </section>
  );
}
