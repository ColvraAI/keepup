// Builds db/pinned-sources.json from data/replay: the text behind a published finding that only an online run could read.
// Only libraries whose release notes were read and libraries a move points at: the rest of the registry pages are version lists no finding cites.
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { PinnedSources } from '../src/pinned-sources.ts';

const OPENROUTER_LIST = 'https://openrouter.ai/models';
const NOTE = 'Generated by scripts/pin-replay.ts from data/replay. Never edited by hand. keepup verify reads this as text behind a source.';

function jsonFiles(dir: string): { name: string; text: string }[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((name) => name.endsWith('.json')).sort().map((name) => ({ name, text: readFileSync(join(dir, name), 'utf8') }));
}

function notesIn(notesDir: string): Map<string, { url: string; text: string }> {
  const notes = new Map<string, { url: string; text: string }>();
  for (const ecosystem of existsSync(notesDir) ? readdirSync(notesDir).sort() : []) {
    for (const { name, text } of jsonFiles(join(notesDir, ecosystem))) {
      const parsed = JSON.parse(text) as { url?: string; text?: string } | null;
      if (parsed?.url && parsed.text) notes.set(`${ecosystem}/${name}`, { url: parsed.url, text: parsed.text });
    }
  }
  return notes;
}

function registryPage(registryDir: string, key: string): { source: string; text: string } | null {
  const file = join(registryDir, key);
  if (!existsSync(file)) return null;
  const text = readFileSync(file, 'utf8');
  const source = (JSON.parse(text) as { source?: string }).source;
  return source ? { source, text } : null;
}

export function buildPinnedSources(replayDir: string, movesFile: string): PinnedSources {
  const sources: Record<string, string> = {};
  const add = (url: string, text: string) => { sources[url] = sources[url] ? `${sources[url]}\n${text}` : text; };
  const notes = notesIn(join(replayDir, 'notes'));
  const moves = (JSON.parse(readFileSync(movesFile, 'utf8')) as { moves: { ecosystem: string; from: string; to: string }[] }).moves;
  const keys = [...notes.keys(), ...moves.flatMap((move) => [move.from, move.to].map((name) => `${move.ecosystem}/${encodeURIComponent(name)}.json`))];
  for (const key of new Set(keys)) {
    const page = registryPage(join(replayDir, 'registry'), key);
    if (page) add(page.source, page.text);
    const note = notes.get(key);
    if (note) add(note.url, note.text);
  }
  const cards = join(replayDir, 'cards');
  for (const name of existsSync(cards) ? readdirSync(cards).sort() : []) add(`https://huggingface.co/${decodeURIComponent(name.replace(/\.txt$/, ''))}`, readFileSync(join(cards, name), 'utf8'));
  const list = join(replayDir, 'registry', 'openrouter-models.json');
  if (existsSync(list)) add(OPENROUTER_LIST, readFileSync(list, 'utf8'));
  return { note: NOTE, sources };
}
