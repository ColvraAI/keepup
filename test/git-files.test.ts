import { strict as assert } from 'node:assert';
import { existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { after, before, describe, it } from 'node:test';
import { changedFiles, listRepoFiles, repoName, selectFiles, skipReason } from '../src/git-files.ts';
import { type FixtureRepo, fixtureRepo, git } from './helpers.ts';

describe('listRepoFiles', () => {
  let repo: FixtureRepo;
  const big = 'const big = JSON.parse(res.choices[0].message.content);\n' + '// padding line\n'.repeat(150_000);
  before(() => { repo = fixtureRepo('with-node-modules', { 'src/big.ts': big }); });
  after(() => repo.cleanup());

  const assertOnlyRealFiles = (paths: string[]) => {
    assert.deepEqual(paths, ['.gitignore', 'src/app.ts']);
  };

  it('skips node_modules, dist, minified, generated, binary, over 2 MB and .gitignored files', () => {
    const paths = listRepoFiles(repo.path).files.map((f) => f.path).sort();
    assertOnlyRealFiles(paths);
  });

  it('reads a stated commit through git without checking anything out', () => {
    writeFileSync(join(repo.path, 'src', 'app.ts'), 'changed in the worktree\n');
    const result = listRepoFiles(repo.path, { commit: repo.commit });
    assertOnlyRealFiles(result.files.map((f) => f.path).sort());
    const app = result.files.find((f) => f.path === 'src/app.ts');
    assert.match(app?.text ?? '', /JSON\.parse/);
    assert.equal(result.commit, repo.commit);
    assert.match(git(repo.path, 'status', '--porcelain'), /src\/app\.ts/);
  });

  it('counts why files were skipped', () => {
    const result = listRepoFiles(repo.path, { commit: repo.commit });
    assert.equal(result.skipped.vendored, 1); // node_modules
    assert.equal(result.skipped.minified, 2); // app.min.js and bundle.js, one very long line
    assert.equal(result.skipped.generated, 2); // dist/ and the @generated header
    assert.ok(result.skipped.binary >= 1);
    assert.ok(result.skipped.too_big >= 1);
  });

  it('fails with a clear error on something that is not a git repo', () => {
    const plain = mkdtempSync(join(tmpdir(), 'keepup-plain-'));
    try {
      assert.throws(() => listRepoFiles(plain), /git/i);
    } finally {
      rmSync(plain, { recursive: true, force: true });
    }
  });

  it('refuses a commit that looks like an option', () => {
    assert.throws(() => listRepoFiles(repo.path, { commit: '--output=/tmp/x' }), /commit/i);
  });
});

describe('selectFiles', () => {
  it('filters an in-memory iterable by the same rules', () => {
    const files = [
      { path: 'src/a.ts', text: 'ok\n' },
      { path: 'node_modules/x/index.js', text: 'no\n' },
      { path: 'lib/a.min.js', text: 'no\n' },
      { path: 'gen.ts', text: '// Code generated by protoc. DO NOT EDIT.\n' },
      { path: 'bin.ts', text: 'a\u0000b' },
      { path: 'huge.ts', text: 'x'.repeat(2 * 1024 * 1024 + 1) },
    ];
    assert.deepEqual([...selectFiles(files)].map((f) => f.path), ['src/a.ts']);
  });

  it('keeps tests and examples, which are not vendored', () => {
    assert.equal(skipReason('examples/minimal/anthropic.toml'), null);
    assert.equal(skipReason('crates/aura/tests/smoke.rs'), null);
    assert.equal(skipReason('vendor/x.go'), 'vendored');
    assert.equal(skipReason('package-lock.json'), 'generated');
  });
});

describe('repoName', () => {
  it('reads owner/name from the origin remote and never prints a token in the URL', () => {
    const repo = fixtureRepo('quiet');
    try {
      git(repo.path, 'remote', 'add', 'origin', 'https://x-access-token:secretvalue@github.com/acme/quiet-app.git');
      assert.equal(repoName(repo.path), 'acme/quiet-app');
    } finally {
      repo.cleanup();
    }
  });

  it('falls back to the folder name', () => {
    const repo = fixtureRepo('quiet');
    try {
      assert.ok(repoName(repo.path).startsWith('keepup-quiet-'));
    } finally {
      repo.cleanup();
    }
  });
});

describe('changedFiles', () => {
  function branched(): { repo: FixtureRepo; base: string } {
    const repo = fixtureRepo('quiet');
    mkdirSync(join(repo.path, 'caf\u00e9'));
    writeFileSync(join(repo.path, 'caf\u00e9', 'answer.ts'), 'x\n');
    writeFileSync(join(repo.path, 'second.ts'), 'y\n');
    git(repo.path, 'add', '-A');
    git(repo.path, '-c', 'commit.gpgsign=false', 'commit', '-q', '-m', 'the change');
    return { repo, base: repo.commit };
  }

  it('names the files between the base and HEAD, whatever their names hold', () => {
    const { repo, base } = branched();
    try {
      assert.deepEqual(changedFiles(repo.path, base), ['caf\u00e9/answer.ts', 'second.ts']);
    } finally {
      repo.cleanup();
    }
  });

  it('leaves out what is only in the worktree, and runs no clean filter', () => {
    const { repo, base } = branched();
    const marker = join(repo.path, 'filter-ran');
    try {
      writeFileSync(join(repo.path, '.git', 'info', 'attributes'), '* filter=steer\n');
      git(repo.path, 'config', 'filter.steer.clean', `touch ${marker}; cat`);
      writeFileSync(join(repo.path, 'second.ts'), 'edited\n');
      writeFileSync(join(repo.path, 'untracked.ts'), 'z\n');
      assert.deepEqual(changedFiles(repo.path, base), ['caf\u00e9/answer.ts', 'second.ts']);
      assert.ok(!existsSync(marker));
    } finally {
      repo.cleanup();
    }
  });

  it('is empty with no base, a base git does not have, a base that is not a commit id, or no repo', () => {
    const { repo, base } = branched();
    try {
      assert.deepEqual(changedFiles(repo.path, null), []);
      assert.deepEqual(changedFiles(repo.path, undefined), []);
      assert.deepEqual(changedFiles(repo.path, 'abc1234'), []);
      assert.deepEqual(changedFiles(repo.path, '--output=steered'), []);
      assert.ok(!existsSync(join(repo.path, 'steered')));
      assert.deepEqual(changedFiles(tmpdir(), base), []);
    } finally {
      repo.cleanup();
    }
  });
});
